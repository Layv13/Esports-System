    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
       esports.controller.AdminController ctrl = new esports.controller.AdminController();
    String err = ctrl.registerManager(
        tfUsername.getText(), new String(pfPassword.getPassword()), tfFullName.getText());
    if (err == null) {
        lblFormStatus.setForeground(new java.awt.Color(16, 185, 129));
        lblFormStatus.setText("Manager registered successfully.");
        tfUsername.setText(""); pfPassword.setText(""); tfFullName.setText("");
        refresh();
    } else {
        lblFormStatus.setForeground(new java.awt.Color(239, 68, 68));
        lblFormStatus.setText(err);
    }
    }//GEN-LAST:event_btnRegisterActionPerformed

    private void btnRemoveManagerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveManagerActionPerformed
         int row = tblManagers.getSelectedRow();
    if (row < 0) { return; }
    String username = (String) tblManagers.getModel().getValueAt(row, 1);
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Remove manager '" + username + "' and their team?",
        "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        esports.controller.AdminController ctrl = new esports.controller.AdminController();
        ctrl.removeManager(username);
        refresh();
    }
    }//GEN-LAST:event_btnRemoveManagerActionPerformed


