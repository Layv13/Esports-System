public void refresh() {
    esports.controller.AdminController ctrl = new esports.controller.AdminController();
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblManagers.getModel();
    model.setRowCount(0);
    for (esports.model.Manager m : ctrl.getManagers()) {
        esports.model.Team t = ctrl.getTeamById(m.hasTeam() ? m.getTeamId() : "");
        model.addRow(new Object[]{
            m.getFullName(), m.getUsername(),
            t != null ? t.getName() : "— No team"
        });
    }
}
